// `task mcp:supply-chain` — "Can a CSO accept what we ship?" Generates the CycloneDX SBOM with
// npm's own `npm sbom`, checks it against supply-chain/approved.json and writes the register
// the owner signs (docs/supply-chain/register.md). Fails on an unregistered package or a
// licence outside the allowed list. With --release it also fails while any entry awaits the
// owner's signature.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const repo = path.dirname(root);
const release = process.argv.includes('--release');
const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
const pkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'));
const register = JSON.parse(readFileSync(path.join(root, 'supply-chain', 'approved.json'), 'utf8'));

const sbomText = execFileSync(npm, ['sbom', '--sbom-format', 'cyclonedx', '--omit=dev'], {
  cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, shell: process.platform === 'win32',
});
const sbom = JSON.parse(sbomText);
const licence = (c) => (c.licenses ?? []).map((l) => l.license?.id ?? l.license?.name ?? l.expression).join(' OR ') || 'UNKNOWN';

const problems = [];
const direct = { ...pkg.dependencies, ...pkg.devDependencies };
for (const name of Object.keys(direct)) {
  if (!register.packages[name]) problems.push(`unregistered package: ${name} (add it to supply-chain/approved.json with why, value and what-if)`);
}
const allowed = new Set(register.allowedLicences);
for (const c of sbom.components) {
  const ids = licence(c).split(' OR ');
  if (!ids.some((id) => allowed.has(id))) problems.push(`licence not allowed: ${c.name}@${c.version} (${licence(c)})`);
}
const pending = Object.entries({ ...register.packages, ...register.releaseTools }).filter(([, e]) => e.status !== 'approved');
if (release && pending.length) problems.push(`awaiting owner signature: ${pending.map(([n]) => n).join(', ')}`);

const byLicence = {};
for (const c of sbom.components) byLicence[licence(c)] = (byLicence[licence(c)] ?? 0) + 1;
const today = new Date().toLocaleDateString('en-CA');
const row = (name, e) => `| \`${name}\` | ${e.scope ?? 'release tool'} | ${e.class} | ${e.owner} | ${e.why} | ${e.value ?? '—'} | ${e.whatIf ?? e.advisory ?? '—'} | **${e.status}** |`;
const md = `# Command Center supply-chain register

Generated by \`task mcp:supply-chain\` from \`npm sbom\` (CycloneDX ${sbom.specVersion}) on ${today} for \`${pkg.name}@${pkg.version}\`. Do not edit by hand: change \`mcp-server/supply-chain/approved.json\` and re-run.

**Policy.** ${register.policy}

## Packages that need a decision

The owner signs by setting \`"status": "approved"\` for each entry in \`approved.json\`. A release fails while any entry is pending.

| Package | Scope | Class | Owner | Why | Value | What if not | Status |
|---|---|---|---|---|---|---|---|
${Object.entries(register.packages).map(([n, e]) => row(n, e)).join('\n')}
${Object.entries(register.releaseTools).map(([n, e]) => row(n, e)).join('\n')}

## What ships (measured)

- **${sbom.components.length} components** in the installed package (runtime dependencies and theirs; dev tools excluded).
- **Licences:** ${Object.entries(byLicence).map(([l, n]) => `${l} ${n}`).join(', ')}.
- **Gate result:** ${problems.length ? `FAIL — ${problems.length} problem(s)` : pending.length ? `checks PASS; **${pending.length} entr${pending.length === 1 ? 'y awaits' : 'ies await'} the owner's signature, so this is not yet release-approved**` : 'PASS, every entry signed'}.

<details><summary>All ${sbom.components.length} shipped components</summary>

| Component | Version | Licence |
|---|---|---|
${sbom.components.map((c) => `| ${c.name} | ${c.version} | ${licence(c)} |`).sort().join('\n')}

</details>
`;

mkdirSync(path.join(repo, 'docs', 'supply-chain'), { recursive: true });
writeFileSync(path.join(repo, 'docs', 'supply-chain', 'register.md'), md);
const evidence = path.join(repo, 'tmp', 'command-center', 'evidence');
mkdirSync(evidence, { recursive: true });
writeFileSync(path.join(evidence, `sbom-${pkg.version}-${today}.cdx.json`), sbomText);

console.log(`${sbom.components.length} shipped components; licences: ${Object.entries(byLicence).map(([l, n]) => `${l} ${n}`).join(', ')}`);
console.log(`awaiting owner signature: ${pending.length ? pending.map(([n]) => n).join(', ') : 'none'}`);
for (const p of problems) console.log(`FAIL  ${p}`);
console.log(problems.length ? 'FAIL' : pending.length ? 'PASS (checks) — not release-approved until signed' : 'PASS (signed)');
console.log('register: docs/supply-chain/register.md');
process.exitCode = problems.length ? 1 : 0;
